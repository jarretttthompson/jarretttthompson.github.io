/**
 * photo-upload.js
 *
 * Secure photo upload panel for the photo album page.
 * Activated by visiting photo-album.html?upload
 *
 * Security model:
 *   - A GitHub Personal Access Token (PAT) is stored encrypted using AES-GCM.
 *   - The encryption key is derived from a password via PBKDF2 (200k iterations, SHA-256).
 *   - Wrong password → decryption fails → no API access.
 *   - Correct password → PAT is decrypted in-memory and used for GitHub API calls only.
 *   - Run setup-encryption.html locally to generate your ENCRYPTED_PAT blob.
 */

// ── Config ──────────────────────────────────────────────────────────────────
const REPO_OWNER = "jarretttthompson";
const REPO_NAME  = "jarretttthompson.github.io";
const PHOTO_DIR  = "images/photo album";
const MANIFEST   = "photo-album.json";
const MAX_PX     = 1600;   // longest side after resize (px)
const JPEG_Q     = 0.85;   // JPEG compression quality

// ── Encrypted PAT ───────────────────────────────────────────────────────────
// Replace this null with the object generated by setup-encryption.html
// e.g.  const ENCRYPTED_PAT = { salt: "…", iv: "…", data: "…" };
const ENCRYPTED_PAT = null;

// ── Crypto helpers ──────────────────────────────────────────────────────────
function b64ToBytes(b64) {
  return Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
}

async function deriveKey(password, saltBytes) {
  const raw = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(password),
    "PBKDF2",
    false,
    ["deriveKey"],
  );
  return crypto.subtle.deriveKey(
    { name: "PBKDF2", salt: saltBytes, iterations: 200_000, hash: "SHA-256" },
    raw,
    { name: "AES-GCM", length: 256 },
    false,
    ["decrypt"],
  );
}

async function decryptPat(password, blob) {
  const salt    = b64ToBytes(blob.salt);
  const iv      = b64ToBytes(blob.iv);
  const data    = b64ToBytes(blob.data);
  const key     = await deriveKey(password, salt);
  const decoded = await crypto.subtle.decrypt({ name: "AES-GCM", iv }, key, data);
  return new TextDecoder().decode(decoded);
}

// ── Image helpers ────────────────────────────────────────────────────────────
function resizeAndEncode(file) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    const url = URL.createObjectURL(file);
    img.onload = () => {
      URL.revokeObjectURL(url);
      const { naturalWidth: w, naturalHeight: h } = img;
      const scale  = Math.min(1, MAX_PX / Math.max(w, h));
      const cw     = Math.round(w * scale);
      const ch     = Math.round(h * scale);
      const canvas = Object.assign(document.createElement("canvas"), { width: cw, height: ch });
      canvas.getContext("2d").drawImage(img, 0, 0, cw, ch);
      canvas.toBlob(
        (blob) => {
          const reader = new FileReader();
          reader.onload  = () => resolve(reader.result.split(",")[1]); // base64 only
          reader.onerror = reject;
          reader.readAsDataURL(blob);
        },
        "image/jpeg",
        JPEG_Q,
      );
    };
    img.onerror = reject;
    img.src = url;
  });
}

// ── GitHub API helpers ───────────────────────────────────────────────────────
function ghFetch(path, token, opts = {}) {
  return fetch(
    `https://api.github.com/repos/${REPO_OWNER}/${REPO_NAME}/contents/${encodeURIComponent(path).replace(/%2F/g, "/")}`,
    {
      ...opts,
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "Content-Type": "application/json",
        ...(opts.headers ?? {}),
      },
    },
  );
}

async function getFile(path, token) {
  const res = await ghFetch(path, token);
  if (res.status === 404) return null;
  if (!res.ok) throw new Error(`GitHub GET ${path} failed: ${res.status}`);
  return res.json(); // { content (base64 w/ newlines), sha, … }
}

async function putFile(path, token, message, content64, sha) {
  const body = { message, content: content64 };
  if (sha) body.sha = sha;
  const res = await ghFetch(path, token, { method: "PUT", body: JSON.stringify(body) });
  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err.message ?? `GitHub PUT ${path} failed: ${res.status}`);
  }
  return res.json();
}

// ── Upload orchestration ────────────────────────────────────────────────────
async function uploadPhoto({ file, caption, token, onStatus }) {
  onStatus("Compressing image…");
  const imageB64 = await resizeAndEncode(file);

  const ts       = Date.now();
  const filename = `upload-${ts}.jpg`;
  const imgPath  = `${PHOTO_DIR}/${filename}`;

  onStatus("Uploading image to GitHub…");
  await putFile(imgPath, token, `photo: add ${filename}`, imageB64, null);

  onStatus("Updating photo manifest…");
  const mf      = await getFile(MANIFEST, token);
  let photos    = [];
  let sha;
  if (mf) {
    sha    = mf.sha;
    photos = JSON.parse(atob(mf.content.replace(/\n/g, "")));
  }
  const entry      = { src: imgPath, alt: caption.trim() || "N" };
  photos.unshift(entry); // newest first → shows at top of album
  const newContent = btoa(unescape(encodeURIComponent(JSON.stringify(photos, null, 2))));
  await putFile(MANIFEST, token, "photo: update manifest", newContent, sha);

  onStatus("✓ Uploaded! Your photo will appear in the album in about 60 seconds.");
}

