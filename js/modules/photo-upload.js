// ── Init ─────────────────────────────────────────────────────────────────────
export function initPhotoUpload() {
  // Only activate when ?upload is in the URL
  if (!new URLSearchParams(location.search).has("upload")) return;

  // Inject scoped styles
  const style = document.createElement("style");
  style.textContent = PANEL_CSS;
  document.head.appendChild(style);

  // Build panel
  const panel = document.createElement("div");
  panel.id        = "photo-upload-panel";
  panel.className = "neon-inner-panel relative p-4 md:p-6";
  panel.style.marginBottom = "1.25rem";
  panel.innerHTML = PANEL_HTML;

  // Insert before the album wall
  const wall   = document.querySelector(".album-wall");
  const parent = wall?.parentElement ?? document.querySelector(".album-main") ?? document.querySelector(".site-shell-content");
  if (!parent) return;
  parent.insertBefore(panel, wall ?? parent.firstChild);

  // Element references
  const pwInput   = panel.querySelector("#upl-pw");
  const unlockBtn = panel.querySelector("#upl-unlock");
  const lockErr   = panel.querySelector("#upl-lock-err");
  const lockDiv   = panel.querySelector("#upl-lock");
  const formDiv   = panel.querySelector("#upl-form");
  const fileInput = panel.querySelector("#upl-file");
  const preview   = panel.querySelector("#upl-preview");
  const captionIn = panel.querySelector("#upl-caption");
  const submitBtn = panel.querySelector("#upl-submit");
  const statusEl  = panel.querySelector("#upl-status");

  let token = null; // set after successful unlock

  // ── Unlock ─────────────────────────────────────────────────────────────
  async function tryUnlock() {
    lockErr.style.display = "none";
    if (!ENCRYPTED_PAT) {
      lockErr.textContent = "No encrypted token configured — run setup-encryption.html first.";
      lockErr.style.display = "block";
      return;
    }
    unlockBtn.disabled = true;
    try {
      token = await decryptPat(pwInput.value, ENCRYPTED_PAT);
      lockDiv.style.display = "none";
      formDiv.style.display = "block";
    } catch {
      lockErr.style.display = "block";
      pwInput.value = "";
      pwInput.focus();
    } finally {
      unlockBtn.disabled = false;
    }
  }

  unlockBtn.addEventListener("click", tryUnlock);
  pwInput.addEventListener("keydown", (e) => { if (e.key === "Enter") tryUnlock(); });

  // ── File preview ───────────────────────────────────────────────────────
  fileInput.addEventListener("change", () => {
    const file = fileInput.files[0];
    if (!file) return;
    if (preview._objectUrl) URL.revokeObjectURL(preview._objectUrl);
    preview._objectUrl  = URL.createObjectURL(file);
    preview.src         = preview._objectUrl;
    preview.style.display = "block";
  });

  // ── Submit ─────────────────────────────────────────────────────────────
  submitBtn.addEventListener("click", async () => {
    const file = fileInput.files[0];
    if (!file) {
      statusEl.style.color = "#ff41af";
      statusEl.textContent = "Please choose a photo first.";
      return;
    }
    submitBtn.disabled   = true;
    statusEl.style.color = "rgba(0,255,159,0.7)";
    statusEl.textContent = "";

    try {
      await uploadPhoto({
        file,
        caption: captionIn.value,
        token,
        onStatus: (msg) => { statusEl.textContent = msg; },
      });
      // Reset form after success
      fileInput.value      = "";
      captionIn.value      = "";
      preview.style.display = "none";
      if (preview._objectUrl) {
        URL.revokeObjectURL(preview._objectUrl);
        preview._objectUrl = null;
      }
    } catch (err) {
      statusEl.style.color = "#ff41af";
      statusEl.textContent = `Upload failed: ${err.message}`;
    } finally {
      submitBtn.disabled = false;
    }
  });
}
